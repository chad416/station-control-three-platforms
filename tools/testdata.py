"""The test data of the bench, read once from the Siemens data block and written for the other platforms.

Source of truth: siemens/scl/test/DB_TestData.scl (generated in the door-handle project from its
Python model; 10 recorded curves, 14 replay cases with expected values, limits, envelope).

    python tools/testdata.py           # writes codesys/src/GVL_TestData.st and results/testdata.json

The Logix files take the same values from results/testdata.json (tools/make_logix.py).
"""

from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCL = ROOT / "siemens" / "scl" / "test" / "DB_TestData.scl"

_DECL = re.compile(r"^\s*(\w+)\s*:\s*(Array\[(\d+)\.\.(\d+)\] of (\w+)|\w+)\s*;", re.I)
_ASSIGN = re.compile(r"^\s*(\w+)(?:\[(\d+)\])?\s*:=\s*([^;]+);")


def read_db(path: Path = SCL) -> dict:
    """Variables of the data block: name -> {type, lo, hi, value}; arrays as lists over lo..hi."""
    text = path.read_text(encoding="utf-8")
    head, body = text.split("\nBEGIN", 1)
    var: dict[str, dict] = {}
    order: list[str] = []
    for line in head.splitlines():
        m = _DECL.match(line)
        if not m or m.group(1).upper() in ("VAR", "END_VAR"):
            continue
        name = m.group(1)
        if m.group(3) is not None:
            lo, hi, typ = int(m.group(3)), int(m.group(4)), m.group(5)
            var[name] = {"type": typ, "lo": lo, "hi": hi, "value": [_zero(typ)] * (hi - lo + 1)}
        else:
            var[name] = {"type": m.group(2), "value": _zero(m.group(2))}
        order.append(name)
    for line in body.splitlines():
        m = _ASSIGN.match(line)
        if not m:
            continue
        name, idx, val = m.group(1), m.group(2), m.group(3).strip()
        v = var[name]
        x = _parse(v["type"], val)
        if idx is None:
            v["value"] = x
        else:
            v["value"][int(idx) - v["lo"]] = x
    return {"order": order, "var": var}


def _zero(typ: str):
    t = typ.lower()
    return False if t == "bool" else 0.0 if t == "real" else 0


def _parse(typ: str, s: str):
    t = typ.lower()
    if t == "bool":
        return s.upper() == "TRUE"
    if t == "real":
        return float(s)
    return int(s)


def _fmt(typ: str, x) -> str:
    t = typ.lower()
    if t == "bool":
        return "TRUE" if x else "FALSE"
    if t == "real":
        r = repr(float(x))
        m, _, e = r.partition("e")
        if "." not in m:
            m += ".0"
        return m + ("E" + e if e else "")
    return str(int(x))


def write_codesys(db: dict, path: Path) -> None:
    path.write_text("\n".join(codesys_lines(db)) + "\n", encoding="utf-8")


def codesys_lines(db: dict) -> list[str]:
    """Global variable list with initial values. CODESYS keeps the Siemens array bounds."""
    lines = [
        "// Generated by tools/testdata.py from siemens/scl/test/DB_TestData.scl. Do not edit.",
        "// Recorded force-travel curves, the evaluation recipe and the expected values of the 14 replay cases.",
        "{attribute 'qualified_only'}",
        "VAR_GLOBAL",
    ]
    for name in db["order"]:
        v = db["var"][name]
        typ = v["type"].upper().replace("REAL", "REAL")
        if "lo" in v:
            vals = ", ".join(_fmt(v["type"], x) for x in v["value"])
            lines.append(f"    {name} : ARRAY[{v['lo']}..{v['hi']}] OF {v['type'].upper()} := [{vals}];")
        else:
            lines.append(f"    {name} : {typ} := {_fmt(v['type'], v['value'])};")
    lines.append("END_VAR")
    return lines


def main() -> None:
    db = read_db()
    write_codesys(db, ROOT / "codesys" / "src" / "GVL_TestData.st")
    flat = {n: db["var"][n]["value"] for n in db["order"]}
    bounds = {n: [db["var"][n]["lo"], db["var"][n]["hi"]] for n in db["order"] if "lo" in db["var"][n]}
    (ROOT / "results" / "testdata.json").write_text(
        json.dumps({"source": "siemens/scl/test/DB_TestData.scl", "bounds": bounds, "values": flat}),
        encoding="utf-8")
    print("NCases", flat["NCases"], "NSamples", flat["NSamples"], "curves", flat["NCurves"])


if __name__ == "__main__":
    main()
